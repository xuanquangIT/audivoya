// Pure renderers: canonical records → harness-specific file text.
import { splitFrontmatter } from './frontmatter.mjs';
import {
  flowList,
  quoted,
  raw,
  tomlMultilineLiteral,
  tomlString,
  yamlFrontmatter,
} from './serialize.mjs';

export const GENERATOR_PATH = 'scripts/agents/sync.mjs';
const MARKER_PATTERN =
  /^(?:<!-- |# )Generated by scripts\/agents\/sync\.mjs from /m;

/** Neutral tool → Claude Code tool names. */
export const CLAUDE_TOOLS = {
  read: ['Read'],
  search: ['Grep', 'Glob'],
  edit: ['Edit', 'Write'],
  execute: ['Bash'],
  web: ['WebFetch', 'WebSearch'],
  agent: ['Agent'],
};
/** Neutral model tier → Claude Code model alias. */
export const CLAUDE_MODELS = {
  inherit: 'inherit',
  fast: 'haiku',
  balanced: 'sonnet',
  strong: 'opus',
};
/** Neutral model tier → Codex `model_reasoning_effort` (inherit = omit). */
export const CODEX_REASONING_EFFORT = {
  inherit: undefined,
  fast: 'low',
  balanced: 'medium',
  strong: 'high',
};
export const READONLY_INSTRUCTION = 'You are read-only: never edit files.';

/**
 * The "do not edit" sentence carried by every generated file.
 * @param {string} source Repo-relative POSIX path of the canonical source.
 */
export function markerText(source) {
  return `Generated by ${GENERATOR_PATH} from ${source}. Edit the source and run npm run agents:sync.`;
}

/** @param {string} source */
export function markdownMarker(source) {
  return `<!-- ${markerText(source)} -->`;
}

/** @param {string} source */
export function tomlMarker(source) {
  return `# ${markerText(source)}`;
}

/**
 * True when text carries a generated-file marker (Markdown or TOML form).
 * @param {string} text
 */
export function hasGeneratedMarker(text) {
  return MARKER_PATTERN.test(text);
}

/**
 * Insert the Markdown marker after the frontmatter, leaving every other byte
 * of the document as is. The marker sits between blank lines because Prettier
 * always separates frontmatter from the first block that way.
 * @param {string} text LF-normalized Markdown document.
 * @param {string} source
 * @returns {string}
 */
export function insertMarkdownMarker(text, source) {
  const marker = markdownMarker(source);
  const split = splitFrontmatter(text);
  if (!split) return `${marker}\n\n${text}`;
  const head = split.head.endsWith('\n') ? split.head : `${split.head}\n`;
  if (split.body === '') return `${head}\n${marker}\n`;
  return `${head}\n${marker}${split.body.startsWith('\n') ? '\n' : '\n\n'}${split.body}`;
}

/**
 * Assemble a generated Markdown file: frontmatter, marker, preamble, body.
 * @param {string | null} frontmatter Output of `yamlFrontmatter`, or null.
 * @param {string} source
 * @param {string} body Trimmed body.
 * @param {string[]} [preamble] Lines placed before the body as one paragraph.
 */
function markdownDocument(frontmatter, source, body, preamble = []) {
  const blocks = [markdownMarker(source), preamble.join('\n'), body].filter(
    Boolean,
  );
  return `${frontmatter ? `${frontmatter}\n` : ''}${blocks.join('\n\n')}\n`;
}

/**
 * Tell harnesses without skill preloading which skills to read first.
 * @param {{ skills: string[] }} agent
 * @returns {string[]}
 */
function skillsPreamble(agent) {
  if (!agent.skills.length) return [];
  const paths = agent.skills.map((skill) => `.agents/skills/${skill}/SKILL.md`);
  return [`Read these skills before starting: ${paths.join(', ')}.`];
}

/**
 * `.claude/agents/<name>.md` (also read by Cursor and VS Code Copilot).
 * @param {import('./sources.mjs').Agent} agent
 */
export function renderClaudeAgent(agent) {
  const frontmatter = yamlFrontmatter([
    ['name', agent.name],
    ['description', agent.description],
    ['tools', agent.tools.flatMap((tool) => CLAUDE_TOOLS[tool]).join(', ')],
    ['model', CLAUDE_MODELS[agent.tier]],
    ['readonly', agent.readonly || undefined],
    ['skills', agent.skills.length ? agent.skills : undefined],
  ]);
  return markdownDocument(frontmatter, agent.source, agent.body);
}

/**
 * `.github/agents/<name>.agent.md` (GitHub Copilot custom agent).
 * @param {import('./sources.mjs').Agent} agent
 */
export function renderCopilotAgent(agent) {
  const frontmatter = yamlFrontmatter([
    ['name', agent.name],
    ['description', agent.description],
    ['tools', flowList(agent.tools)],
  ]);
  return markdownDocument(
    frontmatter,
    agent.source,
    agent.body,
    skillsPreamble(agent),
  );
}

/**
 * `.codex/agents/<name>.toml` (Codex custom agent). Codex accepts any
 * non-empty `name`, so hyphenated names are kept as is.
 * @param {import('./sources.mjs').Agent} agent
 */
export function renderCodexAgent(agent) {
  const preamble = [
    ...(agent.readonly ? [READONLY_INSTRUCTION] : []),
    ...skillsPreamble(agent),
  ];
  const instructions = [preamble.join('\n'), agent.body]
    .filter(Boolean)
    .join('\n\n');
  const effort = CODEX_REASONING_EFFORT[agent.tier];
  const lines = [
    tomlMarker(agent.source),
    `name = ${tomlString(agent.name)}`,
    `description = ${tomlString(agent.description)}`,
    ...(effort ? [`model_reasoning_effort = ${tomlString(effort)}`] : []),
    `developer_instructions = ${tomlMultilineLiteral(`${instructions}\n`)}`,
  ];
  return `${lines.join('\n')}\n`;
}

/**
 * `.claude/rules/<name>.md`; always-apply rules have no frontmatter.
 * @param {import('./sources.mjs').Rule} rule
 */
export function renderClaudeRule(rule) {
  const frontmatter = rule.alwaysApply
    ? null
    : yamlFrontmatter([['paths', rule.paths]]);
  return markdownDocument(frontmatter, rule.source, rule.body);
}

/**
 * `.cursor/rules/<name>.mdc`; globs stay an unquoted comma string.
 * @param {import('./sources.mjs').Rule} rule
 */
export function renderCursorRule(rule) {
  const frontmatter = yamlFrontmatter([
    ['description', rule.description],
    ['globs', rule.alwaysApply ? undefined : raw(rule.paths.join(','))],
    ['alwaysApply', rule.alwaysApply],
  ]);
  return markdownDocument(frontmatter, rule.source, rule.body);
}

/**
 * `.github/instructions/<name>.instructions.md` (Copilot path instructions).
 * @param {import('./sources.mjs').Rule} rule
 */
export function renderCopilotInstructions(rule) {
  const frontmatter = yamlFrontmatter([
    ['applyTo', quoted(rule.alwaysApply ? '**' : rule.paths.join(','))],
    ['description', rule.description],
  ]);
  return markdownDocument(frontmatter, rule.source, rule.body);
}
